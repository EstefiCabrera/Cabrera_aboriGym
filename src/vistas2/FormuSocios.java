    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        if(txtDni.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Por favor ingrese un DNI");
        return;
        }
        try{
            String dniBuscado = txtDni.getText();
            Socio sb = socioData.buscarSocioPorDni(dniBuscado);
            
            if(sb !=null){
                txtIdSocio.setText(String.valueOf(sb.getIdSocio()));
                txtNombre.setText(sb.getNombre());
                txtApellido.setText(sb.getApellido());
                txtEdad.setText(String.valueOf(sb.getEdad()));
                txtCorreo.setText(sb.getCorreo());
                txtTelefono.setText(sb.getTelefono());
                chekEstado.setSelected(sb.isEstado());
                
                txtIdSocio.setEnabled(false);
                btnGuardar.setEnabled(false);
                btnModificar.setEnabled(true);
                btnBaja.setEnabled(true);
            }else{
                limpiarCampos();
                btnGuardar.setEnabled(true);
                btnModificar.setEnabled(false);
                btnBaja.setEnabled(false);
            }     
         }catch (Exception e){
            JOptionPane.showMessageDialog(null, "Error al procesar la búsqueda: "+e.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if(txtDni.getText().isEmpty()|| txtNombre.getText().isEmpty()||txtApellido.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Por favor complete Dni, nombre y apellido");
        return;
        }
        String correo = txtCorreo.getText().trim();
        if(!correo.contains("@")|| !correo.contains(".")){
            JOptionPane.showMessageDialog(this, "Por favor ingrese un correo electronico válido");
            txtCorreo.requestFocus();
        return;
        }
        try{
            Socio ns = new Socio();
            ns.setDni(txtDni.getText());
            ns.setNombre(txtNombre.getText());           
            ns.setApellido(txtApellido.getText());
            ns.setEdad(Integer.parseInt(txtEdad.getText()));
            ns.setCorreo(txtCorreo.getText());
            ns.setTelefono(txtTelefono.getText());
            ns.setEstado(chekEstado.isSelected());
            
            SocioData sd = new SocioData(conexion);
            sd.guardarSocio(ns);
            
            limpiarCampos();
            txtIdSocio.setEnabled(false);
            btnGuardar.setEnabled(false);
            btnModificar.setEnabled(false);
            btnBaja.setEnabled(false);
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "La edad debe ser un número entero");           
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error en el formulario: "+e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

