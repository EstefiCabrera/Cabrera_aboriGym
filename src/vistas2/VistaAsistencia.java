    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (jcbSocios.getSelectedItem()==null || jcbClases.getSelectedItem()==null){
            JOptionPane.showMessageDialog(this, "Por favor, seleccione un socio y una clase");
            return;
        }
        if(jFechaAsis.getDate()==null){
            JOptionPane.showMessageDialog(this, "Por favor, seleccione una fecha válida");
            return;    
        }
        try{
            Socio socioSelec = (Socio) jcbSocios.getSelectedItem();
            ClaseGym claseSelec = (ClaseGym) jcbClases.getSelectedItem();
            Date fechaCombo = jFechaAsis.getDate();
            LocalDate fechaLocal = fechaCombo.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            //Instanciamos el objeto modelo Asistencia y se pasan los datos
            Asistencia nuevaAsist = new Asistencia();
            nuevaAsist.setSocio(socioSelec);
            nuevaAsist.setClase(claseSelec);
            nuevaAsist.setFechaAsistencia(fechaLocal);
            
            asistenciaData.registrarAsistencia(nuevaAsist);
            limpiarCampos();
            dibujarCupos();
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error al procesar los datos: "+e.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

