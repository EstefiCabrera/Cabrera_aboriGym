    private void limpiarCampos(){
        if(jcbSocios.getItemCount()>0){
            jcbSocios.setSelectedIndex(0);
        }
        if(jcbClases.getItemCount()>0){
            jcbClases.setSelectedIndex(0);
        }
        jFechaAsis.getJCalendar().setMinSelectableDate(new Date());
    }
