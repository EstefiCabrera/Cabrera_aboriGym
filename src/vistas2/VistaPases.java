    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (txtIdPase.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Primero debe buscar un pase para poder modificarlo.");
        return;
        }

        try {
            Pase paseModificado = new Pase();
            paseModificado.setIdPase(Integer.parseInt(txtIdPase.getText()));
            paseModificado.setSocio((Socio) jcbSocio.getSelectedItem());
            paseModificado.setCosto(Double.parseDouble(txtCosto.getText()));
            paseModificado.setEstado(chekEstado.isSelected());

            int cantidadDeEntradas = 0;
            int opcionSeleccionada = jcbEntradas.getSelectedIndex();
                if (opcionSeleccionada == 1) {
                    cantidadDeEntradas = 8;
                } else if (opcionSeleccionada == 2) {
                    cantidadDeEntradas = 12;
                } else if (opcionSeleccionada == 3) {
                    cantidadDeEntradas = 20;
                }
            paseModificado.setCantidadEntradas(cantidadDeEntradas);

            LocalDate fechaInicio = jFechaI.getDate().toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            LocalDate fechaFin = jFechaFin.getDate().toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            paseModificado.setFechaInicio(fechaInicio);
            paseModificado.setFechaFin(fechaFin);

            paseData.modificarPase(paseModificado); // Reemplaza por tu método
            limpiarCampos();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al modificar el pase: " + e.getMessage());
        }
    }//GEN-LAST:event_btnModificarActionPerformed

