    private void jFechaFinPropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_jFechaFinPropertyChange
        if ("date".equals(evt.getPropertyName())) {
            Date fechaInicio = jFechaI.getDate();
        if (fechaInicio != null) {
            java.util.Calendar cal = java.util.Calendar.getInstance();
            cal.setTime(fechaInicio);
            cal.add(java.util.Calendar.DAY_OF_YEAR, 30);

            jFechaFin.setDate(cal.getTime());
        }
    }
    }//GEN-LAST:event_jFechaFinPropertyChange

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (jcbSocio.getSelectedIndex() <= 0 || jcbEntradas.getSelectedIndex() <= 0 || jFechaI.getDate() == null) {
            JOptionPane.showMessageDialog(null, "Por favor, complete todos los campos obligatorios.");
        return;
        }

        try {
            Pase nuevoPase = new Pase();

            Socio socioSeleccionado = (Socio) jcbSocio.getSelectedItem();
            nuevoPase.setSocio(socioSeleccionado); 
            
            String textoEntradas = jcbEntradas.getSelectedItem().toString();
            int cantidadDeEntradas = 0;
            int opcionSeleccionada = jcbEntradas.getSelectedIndex();

                if (opcionSeleccionada == 1) {
                    cantidadDeEntradas = 8;
                } else if (opcionSeleccionada == 2) {
                    cantidadDeEntradas = 12;
                } else if (opcionSeleccionada == 3) {
                    cantidadDeEntradas = 20;
                }
            nuevoPase.setCantidadEntradas(cantidadDeEntradas);

            nuevoPase.setCosto(Double.parseDouble(txtCosto.getText()));
            nuevoPase.setEstado(chekEstado.isSelected());

            Date dateInicio = jFechaI.getDate();
            Date dateFin = jFechaFin.getDate();

            LocalDate fechaInicio = dateInicio.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
            LocalDate fechaFin = dateFin.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

            nuevoPase.setFechaInicio(fechaInicio);
            nuevoPase.setFechaFin(fechaFin);
            
            paseData.guardarPase(nuevoPase); 
            
            limpiarCampos();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al registrar el contrato de pase: " + e.getMessage());
        }   
    }//GEN-LAST:event_btnGuardarActionPerformed

