    private void btnBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBajaActionPerformed
        if (txtIdPase.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe buscar un pase para darle de baja.");
        return;
        }
        try {
            int id = Integer.parseInt(txtIdPase.getText());
            int respuesta = javax.swing.JOptionPane.showConfirmDialog(null, "¿Desea dar de baja este pase vencido o cancelado?", "Baja de Pase", javax.swing.JOptionPane.YES_NO_OPTION);

            if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
                paseData.darBajaPase(id); 
                chekEstado.setSelected(false);
                limpiarCampos();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al procesar la baja del pase: " + e.getMessage());
        }
    }//GEN-LAST:event_btnBajaActionPerformed


