    private void cargarComboSocios() {
        jcbSocio.removeAllItems();
        jcbSocio.addItem("Seleccione un socio...");
        try {
            SocioData sd = new SocioData(conexion);
            List<Socio> lista = sd.listarSocios();          
             for (Socio s : lista) {
                if (s.isEstado()) { 
                    jcbSocio.addItem(s);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar socios: " + e.getMessage());
        }
    }
    
    private void limpiarCampos(){
        txtIdPase.setText("");
        txtCosto.setText("");
        jcbSocio.setSelectedIndex(0);
        jcbEntradas.setSelectedIndex(0);
        jFechaI.setDate(null);
        jFechaFin.setDate(null);
        chekEstado.setSelected(true);
        txtIdPase.setEnabled(false);
        btnBuscar.setText("Buscar");
        btnGuardar.setEnabled(true);
        btnModificar.setEnabled(false);
        btnBaja.setEnabled(false);
    }
