    private void btnBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBajaActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe buscar una clase para darle de baja.");
        return;
    }
        try {
            int idClase = Integer.parseInt(txtId.getText());

            int respuesta = JOptionPane.showConfirmDialog(null, 
                "¿Está seguro de que desea dar de baja a esta clase?", 
                "Confirmar Baja Lógica", 
                JOptionPane.YES_NO_OPTION);
            if (respuesta == JOptionPane.YES_OPTION) {
               claseGymData.bajaClase(idClase);
                chekEstado.setSelected(false);
                limpiarCampos();
            }
        } catch (NumberFormatException e) {
           JOptionPane.showMessageDialog(null, "El ID del socio no es válido.");
        } catch (Exception e) {
           JOptionPane.showMessageDialog(null, "Error al procesar la baja: " + e.getMessage());
        }
    }//GEN-LAST:event_btnBajaActionPerformed


