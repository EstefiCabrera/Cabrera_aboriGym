    private void armarCabecera(){     
        modelo.addColumn("Fecha Asistencia");
        modelo.addColumn("Disciplina");
        modelo.addColumn("Horario");
        jtHistorial.setModel(modelo);
    }

    private void cargarComboSocios() {
        jcbSocios.removeAllItems();;
        for(Socio s: socioData.listarSocios()){
            jcbSocios.addItem(s);
        }
    }
